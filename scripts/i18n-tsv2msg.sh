#!/usr/bin/env bash
# scripts/i18n-tsv2msg.sh — turn a translator's TSV into a msgcat catalog.
#
# args: <tsv> <locale-id>
#
# The TSV is `key<TAB>translation` rows, which is what a translator (or
# a translation child) writes: no Tcl quoting to get wrong, no escaping
# to remember. This script does the quoting with Tcl's own `list`, so a
# translation containing braces, quotes or newlines lands in the catalog
# EXACTLY as written.
#
# The msgcat catalog must be sourceable Tcl: msgcat runs it as a script,
# and a quoting error there throws out of ::vi18n::init, which main.tcl
# calls unguarded at startup. So the output is verified by SOURCING it in
# a probe interpreter before it is accepted.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TSV="${1:?usage: i18n-tsv2msg.sh <tsv> <locale-id>}"
LOC="${2:?usage: i18n-tsv2msg.sh <tsv> <locale-id>}"
OUT="$ROOT/veles-desktop/msgs/$LOC.msg"

run_tcl() {
    # Never turn a failed generation or mclocale probe into a second,
    # different-runtime attempt. That used to hide the actual Tcl error
    # and could report a catalog as valid after the first probe failed.
    if command -v direnv >/dev/null 2>&1; then
        # tclsh, not wish: a headless wish can block waiting for a display.
        direnv exec "$ROOT" tclsh "$@"
    else
        tclsh "$@"
    fi
}

# The writer puts every line through ::unsplit::puts (see that file).
export I18N_UNSPLIT="$ROOT/scripts/i18n-unsplit.tcl"
TMP="$(mktemp --suffix=.tcl)"
cat > "$TMP" <<'TCL'
# args: tsv out locale en.yml
lassign $argv tsv out locale enyml
source $::env(I18N_UNSPLIT)

# ── edge whitespace is the SOURCE's, never the translator's ──────────
#
# A leading or trailing space in these strings is LAYOUT, not language:
# "  (none)" is an indented sub-line and " · next: %s" is a suffix that
# gets appended to other text. The 2026-09-21 round shipped ~128 rows
# that had lost (or grown) one, so suffixes welded onto the text before
# them. The value keeps its words and gets exactly the English source's
# edge spaces — en.yml's text for a symbolic key, the key itself
# otherwise. scripts/i18n-catalog-check.tcl checks the result.
proc load_en_symbolic {path} {
    set d [dict create]
    if {$path eq "" || ![file exists $path]} { return $d }
    set fh [open $path r]
    fconfigure $fh -encoding utf-8 -buffersize 1048576
    foreach line [split [read $fh] \n] {
        if {[regexp {^([A-Za-z0-9_]+): "((?:[^"\\]|\\.)*)"\s*$} $line -> k v]} {
            if {$k eq "_version"} { continue }
            dict set d $k [string map [list {\\} "\\" {\"} "\"" {\n} "\n" {\t} "\t"] $v]
        }
    }
    close $fh
    return $d
}
proc edge_normalize {src v} {
    if {[string trim $src " "] eq ""} { return $v }
    regexp {^( *)} $src -> lead
    regexp {( *)$} $src -> trail
    return "$lead[string trim $v { }]$trail"
}
set en_sym [load_en_symbolic $enyml]

set fh [open $tsv r]
fconfigure $fh -encoding utf-8 -buffersize 1048576
set data [read $fh]
close $fh

# Preserve any translation the catalog already has for a key the TSV
# omits, so re-running after a partial pass does not throw work away.
set existing {}
if {[file exists $out]} {
    set fh [open $out r]
    fconfigure $fh -encoding utf-8 -buffersize 1048576
    foreach line [split [read $fh] \n] {
        set line [string trim $line]
        if {![string match "::msgcat::mcset $locale *" $line]} { continue }
        if {[catch { llength $line } n] || $n != 4} { continue }
        dict set existing [lindex $line 2] [lindex $line 3]
    }
    close $fh
}

set rows {}
foreach line [split $data \n] {
    if {[string trim $line] eq ""} { continue }
    if {[string match "#*" [string trimleft $line]]} { continue }
    set tab [string first "\t" $line]
    if {$tab < 0} { continue }
    set k [string range $line 0 [expr {$tab - 1}]]
    set v [string range $line [expr {$tab + 1}] end]
    dict set rows $k $v
}
foreach k [dict keys $existing] {
    if {![dict exists $rows $k]} { dict set rows $k [dict get $existing $k] }
}

set fh [open $out w]
fconfigure $fh -encoding utf-8
::unsplit::puts $fh "# ::msgcat 1.0 — veles-desktop strings, locale $locale."
::unsplit::puts $fh "# GENERATED by scripts/i18n-tsv2msg.sh from a translator's TSV;"
# The same five lines i18n-sync.sh writes — keep the two in step, or
# every run of one rewrites all 46 headers the other wrote.
::unsplit::puts $fh "# scripts/i18n-sync.sh drops dead keys; it never copies English in."
::unsplit::puts $fh "# Keys are the English source strings; values are the translation."
::unsplit::puts $fh "# Missing keys fall back to English (the key itself)."
::unsplit::puts $fh {package require msgcat}
set n 0
foreach k [lsort [dict keys $rows]] {
    set src [expr {[dict exists $en_sym $k] ? [dict get $en_sym $k] : $k}]
    # `list` quotes; never hand-wrap in braces.
    ::unsplit::puts $fh [list ::msgcat::mcset $locale $k [edge_normalize $src [dict get $rows $k]]]
    incr n
}
close $fh
puts $n
TCL

n=$(run_tcl "$TMP" "$TSV" "$OUT" "$LOC" "$ROOT/crates/veles-core/locales/en.yml" | tail -1)
rm -f "$TMP"

# PROVE it loads. A catalog that is not sourceable Tcl is not a
# catalog: it is a startup crash in a translated build — ::vi18n::init
# is called unguarded from main.tcl, and it carries the error out of
# app startup.
#
# The check is `mcload` in the CURRENT interpreter (no child): a child
# interp is a safe one, and msgcat refuses to load there ("package
# require msgcat" throws), which made this probe fail on a GOOD catalog.
VERIFY="$(mktemp --suffix=.tcl)"
cat > "$VERIFY" <<'TCL'
# args: catalog-path
set path [lindex $argv 0]
set dir [file dirname $path]
set id [file rootname [file tail $path]]
package require msgcat
if {[catch { ::msgcat::mcload $dir } err]} {
    puts stderr "mcload: $err" ; exit 1
}
if {[catch { ::msgcat::mclocale $id } err]} {
    puts stderr "mclocale: $err" ; exit 1
}
# Reading the file back through mc proves the mcset calls took effect,
# not merely that the file parsed.
if {[catch { ::msgcat::mc {_i18n_selftest_missing_} } err]} {
    puts stderr "mc: $err" ; exit 1
}
exit 0
TCL
run_tcl "$VERIFY" "$OUT"
rm -f "$VERIFY"

echo "$LOC.msg: $n entries (verified sourceable)"