#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct HookDecl {
    /// The hook name (`public_reply`).
    pub name: String,
    #[serde(default)]
    pub description: String,
}

/// How many processes a plugin runs.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
