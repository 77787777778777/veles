//! The process-plugin protocol, version 1 (PLAN-plugins-installer.md D4).
//!
//! A process plugin is an executable. The gateway runs it once with
//! `--describe` (it prints its [`Manifest`] and exits; no network, no
//! config), then spawns one process per instance and speaks JSON-RPC to
//! it over stdin/stdout ([`crate::jsonrpc`]). The first call is
//! [`method::INITIALIZE`]; the answer is the manifest again, and a
//! protocol number the gateway does not speak ends the process there.
//!
//! Everything a plugin may do to the gateway is a method in [`method`];
//! there is no other channel. The gateway is the only authority on who
//! a sender is ([`method::RESOLVE`]) and on secrets ([`method::SECRET`],
//! only for names the manifest declares), so a plugin never holds a copy
//! of the access model to get wrong.

use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::collections::BTreeMap;

/// The protocol this build speaks. A plugin or a gateway that sees a
/// different number refuses, by name, rather than guessing.
pub const PROTOCOL: u32 = 1;

/// The extension API version (PLAN-extension-api.md D1): what a plugin in
/// a stable tier (a script, an ABI 4 `.so`, a process plugin) may rely on
/// across updates. That is the bridge ops and their script bindings, the
/// hook names, the plugin.toml and manifest keys, this protocol's methods
/// and C ABI 4's header. `docs/extension-api.json` is its published spec,
/// generated by `veles plugins api --write`; any change to that surface
/// bumps this, and the gate's `ext_api` tests fail until it is bumped,
/// written, logged in docs/extension-api-changes.md and documented.
///
/// `0.x` until the first release (any change bumps the minor number),
/// then semver: a new name is a minor bump, a removed or changed one a
/// major bump.
pub const EXT_API_VERSION: &str = "0.9";

/// Method names, both directions.
pub mod method {
    // ── gateway → plugin ──
    /// Request, [`super::InitParams`] → [`super::Manifest`]. The plugin
    /// starts its work here and must answer promptly (the gateway gives
    /// up after its init timeout); long-running work belongs on tasks
    /// it spawns.
    pub const INITIALIZE: &str = "initialize";
    /// Request, an `OutboundMessage` → [`super::Receipt`]. One at a time
    /// per instance, in order.
    pub const DELIVER: &str = "outbound.deliver";
    /// Request, [`super::ShutdownParams`]. The plugin cleans up and
    /// exits; the gateway kills it after a grace period regardless.
    pub const SHUTDOWN: &str = "shutdown";

    // ── plugin → gateway ──
    /// Notification, an `InboundMessage`. The gateway sets the route to
    /// the instance and drops a message for a platform the manifest
    /// does not declare.
    pub const INBOUND: &str = "bus.inbound";
    /// Notification or request, [`super::NoteParams`]: park a
    /// plugin-action note on the transcript (nothing a plugin does is
    /// silent).
    pub const NOTE: &str = "note";
    /// Request, [`super::SecretParams`] → [`super::SecretValue`]. Only a
    /// name the manifest declares; anything else is refused.
    pub const SECRET: &str = "secret.get";
    /// Request, [`super::ResolveParams`] → the gateway's resolved
    /// principal (role and capabilities) for that sender.
    pub const RESOLVE: &str = "acl.resolve";
    /// Request, [`super::GrantParams`] → [`super::GrantResult`]. A scoped,
    /// TTL'd runtime grant for an identity on one of the plugin's own
    /// platforms (the atproto door: a mutual of the operator gets User).
    /// The gateway is the only writer of the ACL; a plugin never holds a
    /// store handle. Refused for an identity outside the plugin's
    /// declared platforms, and `owner` is never grantable.
    pub const GRANT: &str = "pairing.grant_scoped";
    /// Notification, [`super::RoomParams`]: register a public thread's
    /// participant roster so the slopdrop bridge's `[names]`/`[name]`
    /// resolve on that surface. Display only; the ACL keys on the DID.
    pub const ROOM: &str = "thread_room.register";
    /// Request, [`super::ConfigGetParams`] → [`super::ConfigGetValue`]. A
    /// dotted config.toml path the manifest lists in `config_sections`;
    /// anything else is refused (a plugin reads only what it declared).
    pub const CONFIG_GET: &str = "config.get";
    /// Notification, [`super::RecordPostsParams`]: the plugin's delivery
    /// [`super::Receipt`] ids reported for a ledger entry after the fact
    /// (`meta_keys::LEDGER_ENTRY` named it on the outbound message). The
    /// gateway relays it to whoever keeps that ledger (a delivery
    /// observer); the plugin only reports what it posted.
    pub const RECORD_POSTS: &str = "ledger.record_posts";
    /// Request (gateway → plugin, a service), [`super::PostCreateParams`]
    /// → [`super::PostCreated`]: post text as the bot, threaded under a
    /// post when asked. A long text becomes a thread of posts; URLs get
    /// link facets. Generic: the caller decides WHAT is posted (R5: the
    /// slopdrop module's approve reposts an output inline through it).
    pub const POST_CREATE: &str = "post.create";
    /// Request (gateway → plugin, a service),
    /// [`super::DeleteRecordParams`] → `null`: delete one record of the
    /// bot's repo by collection and rkey (a post, a pointer record).
    pub const REPO_DELETE_RECORD: &str = "repo.delete_record";
    /// Request (gateway → plugin, a service), `{}` →
    /// [`super::WhoamiValue`]: which account this plugin acts as — the
    /// session's DID (authoritative, checked against the configured one
    /// at start) and handle. A caller about to touch the bot's repo
    /// reads this first: only the session DID is proof of ownership.
    pub const REPO_WHOAMI: &str = "repo.whoami";
    /// Request (gateway → plugin, a service), [`super::HostedDeleteParams`]
    /// → [`super::HostedDeleted`]: take a hosted copy down — its short
    /// links and the owner-pointer records that keep its blobs alive (the
    /// ids a delivery receipt's `hosted.*` meta reported).
    pub const HOSTED_DELETE: &str = "hosted.delete";
    /// Request (gateway → plugin, a service), [`super::AppviewQueryParams`]
    /// → [`super::AppviewQueryValue`]: one read-only AppView query
    /// (`app.bsky.*.get*`) made AS THE BOT, through its own PDS. The
    /// AppView then answers as it would a signed-in viewer, so an author
    /// who limits their posts to signed-in users is readable, and blocks
    /// apply from the bot's side. Generic: the caller decides what it
    /// asks and what it does with the answer (the trigger engine's
    /// Bluesky link preview).
    pub const APPVIEW_QUERY: &str = "appview.query";
    /// Request (gateway → plugin, a service), [`super::GetRecordParams`]
    /// → [`super::GetRecordValue`]: one PUBLIC record by its AT URI, raw,
    /// from the AppView's record store. No viewer, so no block applies:
    /// what a thread view hides as `#blockedPost` / `#viewBlocked` reads
    /// here, and a record that is gone answers `found: false` (deleted)
    /// rather than an error. Takedowns still apply.
    pub const REPO_GET_RECORD: &str = "repo.get_record";
    /// A service core provides, [`super::VisionDescribeParams`] →
    /// [`super::VisionDescribed`]: describe one image URL through the
    /// `[vision]` route (the same urlguard, size cap and model as the
    /// `vision_analyze` tool). The atproto plugin's automatic alt text.
    pub const VISION_DESCRIBE: &str = "vision.describe";
    /// A service the slopdrop module provides, [`super::BskyEventParams`]
    /// → [`super::BskyEventReplies`]: one Bluesky notification (a like,
    /// a repost, a follow, a quote, a reply, a mention) run through the
    /// trigger rows scoped `platform = atproto`, forwarded to slopdrop's
    /// trigger engine, and each answer shaped by the public-reply policy.
    /// Only the atproto plugin may call it.
    pub const BSKY_EVENT: &str = "bsky.event";

    /// Request (plugin → gateway), [`super::ServiceCallParams`] → the
    /// service's JSON answer: call ANOTHER plugin's service (or core's)
    /// through the gateway's service registry (`veles_core::services`).
    /// Gated by the provider's [`super::ServiceDecl::cap`]: an internal
    /// service (no cap) refuses every process plugin.
    pub const SERVICE_CALL: &str = "service.call";
    /// Request (plugin → gateway), [`super::ServiceNextParams`] → the answer of
    /// the layer BELOW the asking plugin's own: an override point's
    /// provider (or any service's) wrapping what it covers. The token is
    /// the `next` its own request carried, valid while that request runs
    /// (PLAN-extension-api.md D2).
    pub const SERVICE_NEXT: &str = "service.next";
    /// A service (the slopdrop module): forward one channel event to the
    /// bridge's trigger engine, [`super::TriggersForwardParams`] →
    /// [`super::TriggersForwarded`]. What the IRC adapter's Slopdrop
    /// trigger rows call.
    pub const TRIGGERS_FORWARD: &str = "triggers.forward";
    /// A service (the slopdrop module): which events each channel still
    /// has a live binding for, [`super::TriggersMasksParams`] →
    /// [`super::TriggersMasks`]. The forward mask is derived from it.
    pub const TRIGGERS_MASKS: &str = "triggers.masks";
}

/// What a plugin is and what it provides. Printed by `--describe` and
/// answered to [`method::INITIALIZE`].
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct Manifest {
    pub name: String,
    pub version: String,
    pub protocol: u32,
    #[serde(default)]
    pub description: String,
    /// One process, or one per entry of a config array.
    #[serde(default)]
    pub instances: Instances,
    /// The arbiter lease an instance must hold to run, `{instance}`
    /// replaced by its name (`singleton:irc:{instance}`). None = the
    /// instance runs on every node that has the plugin enabled.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub lease: Option<String>,
    /// The platform keys this plugin delivers for. The gateway routes
    /// outbound messages for `(key, instance)` to the instance.
    #[serde(default)]
    pub platforms: Vec<PlatformDecl>,
    /// Dotted config.toml paths the plugin reads (`platforms.irc`). The
    /// gateway passes exactly these subtrees in [`InitParams::config`].
    #[serde(default)]
    pub config_sections: Vec<String>,
    /// Options the setup frontends and installer render generically.
    /// Older plugins without this field have no installer form yet.
    #[serde(default)]
    pub knobs: Vec<super::Knob>,
    /// Secret names the plugin may ask for. Nothing else is given out.
    #[serde(default)]
    pub secrets: Vec<SecretDecl>,
    /// Services the plugin PROVIDES (`veles_core::services`). A process
    /// plugin's are registered for it while it runs, answered by its
    /// `request` handler under the service's name; a module registers
    /// its handlers in `start` and lists them here for the dependency
    /// view.
    #[serde(default)]
    pub services: Vec<ServiceDecl>,
    /// Services the plugin USES from other plugins.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub uses: Vec<UseDecl>,
    /// Hooks the plugin answers (gateway → plugin notifications that
    /// expect an answer), e.g. `public_reply` for the public `/tcl`
    /// decision (D4: with no plugin answering it, a public `/tcl` fails
    /// closed). Declarative; implemented in the plugin's `request`.
    #[serde(default)]
    pub hooks: Vec<HookDecl>,
    /// A per-NODE switch (R6): the env/dotenv name that, when it reads
    /// `false`/`0`/`no`/`off`, keeps this plugin's instances from being
    /// spawned on that node (`IRC_ENABLED`). The host decides before any
    /// lease is asked for — a node whose switch is off must not compete
    /// for a platform it must not run.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub enabled_env: Option<String>,
    /// A per-NODE requirement (R6): the env/dotenv name that must be set
    /// (non-empty) for this plugin's instances to be spawned on that
    /// node (`TELEGRAM_BOT_TOKEN`). Same reason as `enabled_env`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub required_env: Option<String>,
    /// The override points this plugin declares (PLAN-extension-api.md
    /// E4): decisions it asks by name, with its own answer at the bottom,
    /// which any plugin in any tier replaces or wraps with `next`. A
    /// module declares each in `start` (`services::declare_point`), the
    /// listing and the published spec read them here.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub points: Vec<PointDecl>,
}

/// A service a plugin provides to other plugins and to core
/// (`veles_core::services`; docs/plugins.md, "Services").
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct ServiceDecl {
    /// The name, dotted (`appview.query`, `triggers.forward`).
    pub name: String,
    #[serde(default)]
    pub description: String,
    /// Who may call it, decided by the PROVIDER:
    /// - unset: internal — core and in-process modules only (compiled
    ///   into the gateway, the same trust as core); a process plugin or
    ///   a script is refused;
    /// - [`SERVICE_CAP_ANY`]: every caller;
    /// - an ACL capability name (`web`, `shell`, …): a process plugin or
    ///   script call is judged as the session it runs for, whose
    ///   principal must hold that capability.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub cap: Option<String>,
}

/// [`ServiceDecl::cap`] for a service every caller may use.
pub const SERVICE_CAP_ANY: &str = "any";

/// An OVERRIDE POINT (PLAN-extension-api.md D2): a decision core (or a
/// module) asks by name, with its own answer registered at the bottom of
/// the service stack. A plugin in any tier registers a service of the
/// same name and answers instead; it may call `next` (the layer below)
/// and adjust that answer. The schemas are the contract and part of the
/// published extension API.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct PointDecl {
    /// The point's name, dotted like a service (`failover.decide`).
    pub name: String,
    /// One line: what is being decided.
    #[serde(default)]
    pub summary: String,
    /// JSON Schema of what a provider is handed.
    #[serde(default)]
    pub input: serde_json::Value,
    /// JSON Schema of what a provider must answer. The host checks
    /// `type`, `required` and each property's `enum`; an answer outside
    /// it is an error ([`PointDecl::on_error`] decides what follows).
    #[serde(default)]
    pub output: serde_json::Value,
    /// What happens when an override fails (an error, a timeout, an
    /// answer outside `output`).
    #[serde(default)]
    pub on_error: OnError,
    /// How long one layer may take, in milliseconds.
    #[serde(default = "default_point_deadline_ms")]
    pub deadline_ms: u64,
}

fn default_point_deadline_ms() -> u64 {
    30_000
}

/// [`PointDecl::on_error`].
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum OnError {
    /// The layer below answers instead, and a plugin note says why: a
    /// broken override never takes the decision down with it.
    #[default]
    FallThrough,
    /// The caller gets the error.
    Fail,
}

/// A service a plugin USES: what it needs from other plugins, declared
/// so the gateway can show who depends on whom (`/plugins services`)
/// and name the missing provider when a call fails.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct UseDecl {
    /// The service name (`appview.query`).
    pub name: String,
    /// The plugin works without it (a feature is off, or falls back).
    #[serde(default)]
    pub optional: bool,
    /// What it is used for.
    #[serde(default)]
    pub description: String,
}

