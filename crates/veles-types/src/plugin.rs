/// An instance name is a route, part of a lease key and a directory
/// name: letters, digits, `.`, `_` and `-`, at most 64. Checked by the
/// gateway before it spawns anything.
pub fn valid_instance_name(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= 64
        && s != "."
        && s != ".."
        && s.chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-'))
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    /// A manifest from a plugin that only knows the required fields
    /// reads, and means one ungated instance with nothing declared.
    #[test]
    fn a_minimal_manifest_reads() {
        let m: Manifest =
            serde_json::from_value(json!({"name": "x", "version": "1", "protocol": 1})).unwrap();
        assert_eq!(m.instances, Instances::Single);
        assert!(m.lease.is_none() && m.platforms.is_empty() && m.secrets.is_empty());
        assert!(m.knobs.is_empty(), "legacy plugins retain their meaning");
    }

    #[test]
    fn knobs_survive_describe_and_initialize_json() {
        let m = Manifest {
            name: "with-options".into(),
            version: "1".into(),
            protocol: PROTOCOL,
            knobs: vec![crate::Knob::blob_documented(
                "platforms.with-options.enabled",
                "false",
                "the installer renders this from the manifest",
            )],
            ..Default::default()
        };
        let encoded = serde_json::to_value(&m).unwrap();
        assert_eq!(encoded["knobs"][0]["shape"], json!("documented"));
        assert_eq!(serde_json::from_value::<Manifest>(encoded).unwrap(), m);
    }

    #[test]
    fn per_entry_instances_round_trip() {
        let m = Manifest {
            name: "irc".into(),
            version: "1".into(),
            protocol: PROTOCOL,
            instances: Instances::PerEntry {
                array: "platforms.irc.networks".into(),
                name: "name".into(),
            },
            ..Default::default()
        };
        let v = serde_json::to_value(&m).unwrap();
        assert_eq!(v["instances"]["kind"], json!("per_entry"));
        assert_eq!(serde_json::from_value::<Manifest>(v).unwrap(), m);
    }

    #[test]
    fn instance_names_that_could_escape_are_refused() {
        for ok in ["synirc", "irc.IRC4Fun.net", "a_b-1"] {
            assert!(valid_instance_name(ok), "{ok}");
        }
        for bad in ["", ".", "..", "a/b", "a b", "x:y", &"n".repeat(65)] {
            assert!(!valid_instance_name(bad), "{bad}");
        }
    }

    /// `appview.query` reads and never writes: only `app.bsky.*.get*`.
    #[test]
    fn only_appview_reads_are_served() {
        for ok in [
            "app.bsky.feed.getPostThread",
            "app.bsky.actor.getProfile",
            "app.bsky.feed.getPosts",
            "app.bsky.feed.searchPosts",
            "app.bsky.actor.searchActors",
        ] {
            assert!(is_appview_read(ok), "{ok}");
        }
        for bad in [
            "",
            "app.bsky.feed.post",
            "app.bsky.notification.updateSeen",
            "app.bsky.actor.putPreferences",
            "com.atproto.repo.createRecord",
            "com.atproto.server.getSession",
            "app.bsky.feed.get",
            "app.bsky.feed.search",
            "app.bsky.feed.searchPosts?q=x",
            "app.bsky.feed.getPosts.x",
            "app.bsky..getProfile",
            "app.bsky.feed.getPosts?x=1",
            "chat.bsky.convo.getMessages",
        ] {
            assert!(!is_appview_read(bad), "{bad}");
        }
    }

    /// `repo.get_record` takes one record's AT URI, nothing looser.
    #[test]
    fn an_at_uri_names_one_record() {
        assert_eq!(
            at_uri_parts("at://did:plc:abc/app.bsky.feed.post/3mxh"),
            Some(("did:plc:abc", "app.bsky.feed.post", "3mxh"))
        );
        for bad in [
            "",
            "https://bsky.app/profile/a.b/post/3x",
            "at://did:plc:abc",
            "at://did:plc:abc/app.bsky.feed.post",
            "at://did:plc:abc/app.bsky.feed.post/3x/more",
            "at://did:plc:abc//3x",
            "at://did:plc:abc/post/3x",
            "at://did:plc:abc/app.bsky.feed.post/3x?y=1",
            "at://../app.bsky.feed.post/3x z",
        ] {
            assert_eq!(at_uri_parts(bad), None, "{bad}");
        }
    }
}
