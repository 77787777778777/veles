/// An AT URI's three parts, `(repo, collection, rkey)`, when it names one
/// record: `at://` and exactly three non-empty segments.
pub fn at_uri_parts(uri: &str) -> Option<(&str, &str, &str)> {
    let rest = uri.strip_prefix("at://")?;
    let mut segs = rest.split('/');
    let (Some(repo), Some(coll), Some(rkey), None) =
        (segs.next(), segs.next(), segs.next(), segs.next())
    else {
        return None;
    };
    let ok = |s: &str| {
        !s.is_empty()
            && s.chars()
                .all(|c| c.is_ascii_alphanumeric() || "._:~-".contains(c))
    };
    (ok(repo) && ok(coll) && ok(rkey) && coll.contains('.')).then_some((repo, coll, rkey))
}

/// Is `method` one `appview.query` serves: an `app.bsky.*` query whose
/// name starts with `get` or `search`? Every such lexicon is a read
/// (`searchPosts` needs a signed-in viewer: the public AppView answers
/// it 403, the bot's session does not).
pub fn is_appview_read(method: &str) -> bool {
    let Some(rest) = method.strip_prefix("app.bsky.") else {
        return false;
    };
    let mut segs = rest.split('.');
    let (Some(group), Some(name), None) = (segs.next(), segs.next(), segs.next()) else {
        return false;
    };
    !group.is_empty()
        && group.chars().all(|c| c.is_ascii_lowercase())
        && ((name.starts_with("get") && name.len() > 3)
            || (name.starts_with("search") && name.len() > 6))
        && name.chars().all(|c| c.is_ascii_alphanumeric())
}

